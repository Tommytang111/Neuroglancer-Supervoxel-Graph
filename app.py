def prepare_state(
    data_path: Path,
    data: VolumeData,
    paths: StatePaths,
    block_shape_xyz: tuple[int, int, int],
    supervoxels: np.ndarray,
    refresh: Callable[[], None] | None = None,
) -> tuple[nx.Graph, dict[str, Any], list[dict[str, Any]]]:
    """Build or restore the supervoxel graph and all persistent metadata."""

    number_of_supervoxels = int(supervoxels.max(initial=0))
    if number_of_supervoxels == 0:
        number_of_supervoxels = construct_supervoxels(
            data.labels_xyz,
            supervoxels,
            block_shape_xyz,
            refresh=refresh,
        )
        atomic_save_numpy(paths.supervoxels, supervoxels)
        print(f"Saved {number_of_supervoxels} supervoxels to {paths.supervoxels}")

    metadata = make_metadata(
        data_path=data_path,
        data=data,
        block_shape_xyz=block_shape_xyz,
        number_of_supervoxels=number_of_supervoxels,
    )
    atomic_write_json(paths.preprocessing, {"version": 1, "metadata": metadata})

    node_ids = {int(node) for node in np.unique(supervoxels) if node != 0}
    if len(node_ids) != number_of_supervoxels:
        raise ValueError(
            "Supervoxel IDs must be dense from 1 through their maximum value"
        )

    if paths.edits.exists():
        saved = json.loads(paths.edits.read_text(encoding="utf-8"))
        graph, history = graph_from_json(saved, node_ids, metadata)
        print(
            f"Restored {len(history)} edits and {graph.number_of_edges()} graph edges "
            f"from {paths.edits}"
        )
    else:
        graph = build_supervoxel_graph(
            supervoxels, data.labels_xyz, data.resolution_xyz
        )
        history = []
        atomic_write_json(paths.edits, graph_to_json(graph, metadata, history))
        print(f"Saved initial graph to {paths.edits}")

    print(
        f"Graph: {graph.number_of_nodes()} nodes, {graph.number_of_edges()} edges, "
        f"{nx.number_connected_components(graph)} objects"
    )
    return graph, metadata, history


def run() -> int:
    parser = create_argument_parser()
    args = parser.parse_args()
    try:
        crop_size_zyx = parse_positive_triplet(args.crop_size, "--crop-size")
        block_shape_xyz = parse_positive_triplet(args.block_shape, "--block-shape")
    except argparse.ArgumentTypeError as error:
        parser.error(str(error))

    data_path = args.data.expanduser().resolve()
    paths = StatePaths.from_directory(args.state_dir.expanduser())
    paths.directory.mkdir(parents=True, exist_ok=True)
    if args.reset_state:
        reset_known_state_files(paths)

    data = load_cremi_crop(data_path, args.crop, crop_size_zyx)
    cached, _cached_metadata = load_cached_supervoxels(
        paths, data, block_shape_xyz
    )
    supervoxels = (
        cached
        if cached is not None
        else np.zeros(data.labels_xyz.shape, dtype=np.uint32)
    )

    if args.prepare_only:
        graph, metadata, history = prepare_state(
            data_path,
            data,
            paths,
            block_shape_xyz,
            supervoxels,
        )
        # Rewrite older notebook metadata with the stronger content fingerprint.
        atomic_write_json(paths.edits, graph_to_json(graph, metadata, history))
        print("Preparation complete")
        return 0

    neuroglancer.cli.handle_server_arguments(args)
    scene = NeuroglancerScene(data, supervoxels)
    viewer_url = scene.viewer.get_viewer_url()
    print(f"\nNeuroglancer URL:\n{viewer_url}\n")

    if args.bind_address in ("0.0.0.0", "::"):
        print(
            "WARNING: The Neuroglancer Python server is reachable remotely. "
            "The viewer URL contains a secret; do not publish it."
        )
    if not args.no_open_browser:
        webbrowser.open_new_tab(viewer_url)

    if cached is None:
        scene.show_live_supervoxel_construction()

    graph, metadata, history = prepare_state(
        data_path,
        data,
        paths,
        block_shape_xyz,
        supervoxels,
        refresh=scene.invalidate_supervoxels,
    )
    editor = SegmentationEditor(
        scene=scene,
        graph=graph,
        metadata=metadata,
        history=history,
        edits_path=paths.edits,
    )

    print(
        "\nControls:\n"
        "  Shift + left-click        Select seed A\n"
        "  Control/Option + click    Select seed B\n"
        "  M                         Merge selected objects\n"
        "  S                         Split between the two seeds\n"
        "  C                         Clear selections\n"
        "\nPress Ctrl+C in this terminal to stop the application.\n"
    )

    stop_event = threading.Event()

    def request_stop(_signal_number: int, _frame: Any) -> None:
        stop_event.set()

    signal.signal(signal.SIGINT, request_stop)
    signal.signal(signal.SIGTERM, request_stop)

    try:
        while not stop_event.wait(0.5):
            pass
    finally:
        editor.save()
        neuroglancer.stop()
        print("Saved edits and stopped Neuroglancer")
    return 0


def main() -> None:
    try:
        raise SystemExit(run())
    except KeyboardInterrupt:
        raise SystemExit(130) from None
    except Exception as error:
        print(f"ERROR: {error}", file=sys.stderr)
        raise SystemExit(1) from error


if __name__ == "__main__":
    main()
