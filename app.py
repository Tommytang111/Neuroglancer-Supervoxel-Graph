def parse_positive_triplet(value: str, option_name: str) -> tuple[int, int, int]:
    """Parse a CLI value such as ``32,384,384``."""

    try:
        result = tuple(int(part.strip()) for part in value.split(","))
    except ValueError as error:
        raise argparse.ArgumentTypeError(
            f"{option_name} must contain three comma-separated integers"
        ) from error

    if len(result) != 3 or any(part <= 0 for part in result):
        raise argparse.ArgumentTypeError(
            f"{option_name} must contain three positive integers"
        )
    return result  # type: ignore[return-value]


def parse_crop(value: str) -> tuple[slice, slice, slice]:
    """Parse ``Z0:Z1,Y0:Y1,X0:X1`` into NumPy slices."""

    pieces = value.split(",")
    if len(pieces) != 3:
        raise argparse.ArgumentTypeError(
            "--crop must have the form Z0:Z1,Y0:Y1,X0:X1"
        )

    slices: list[slice] = []
    try:
        for piece in pieces:
            start_text, stop_text = piece.split(":", maxsplit=1)
            start = int(start_text)
            stop = int(stop_text)
            if start < 0 or stop <= start:
                raise ValueError
            slices.append(slice(start, stop))
    except ValueError as error:
        raise argparse.ArgumentTypeError(
            "--crop must have increasing non-negative integer bounds"
        ) from error

    return tuple(slices)  # type: ignore[return-value]


def centered_xy_crop(
    full_shape_zyx: Sequence[int], crop_size_zyx: Sequence[int]
) -> tuple[slice, slice, slice]:
    """Match the notebook's default: first Z slices and centered XY crop."""

    z_size = min(int(crop_size_zyx[0]), int(full_shape_zyx[0]))
    y_size = min(int(crop_size_zyx[1]), int(full_shape_zyx[1]))
    x_size = min(int(crop_size_zyx[2]), int(full_shape_zyx[2]))

    z0 = 0
    y0 = max(0, int(full_shape_zyx[1]) // 2 - y_size // 2)
    x0 = max(0, int(full_shape_zyx[2]) // 2 - x_size // 2)

    return (
        slice(z0, z0 + z_size),
        slice(y0, y0 + y_size),
        slice(x0, x0 + x_size),
    )


def validate_crop(
    crop_zyx: Sequence[slice], full_shape_zyx: Sequence[int]
) -> tuple[slice, slice, slice]:
    """Ensure a requested crop fits inside both CREMI datasets."""

    for axis_name, crop_slice, axis_size in zip(
        ("Z", "Y", "X"), crop_zyx, full_shape_zyx
    ):
        start = int(crop_slice.start or 0)
        stop = int(crop_slice.stop or axis_size)
        if start < 0 or stop <= start or stop > axis_size:
            raise ValueError(
                f"Invalid {axis_name} crop {start}:{stop}; axis size is {axis_size}"
            )
    return tuple(crop_zyx)  # type: ignore[return-value]


def find_resolution_zyx(
    file: h5py.File, raw_dataset: h5py.Dataset, label_dataset: h5py.Dataset
) -> np.ndarray:
    """Find the CREMI resolution attribute, which is expressed in ZYX order."""

    candidates: Iterable[h5py.Group | h5py.Dataset] = (
        raw_dataset,
        label_dataset,
        file["volumes"],
        file,
    )
    for candidate in candidates:
        if "resolution" in candidate.attrs:
            resolution = np.asarray(candidate.attrs["resolution"], dtype=float)
            if resolution.shape == (3,) and np.all(resolution > 0):
                return resolution

    raise ValueError(
        "Could not find a positive three-element 'resolution' attribute in the "
        "CREMI HDF5 file"
    )


def load_cremi_crop(
    data_path: Path,
    requested_crop: tuple[slice, slice, slice] | None,
    crop_size_zyx: tuple[int, int, int],
) -> VolumeData:
    """Load and transpose one CREMI crop from ZYX into XYZ order."""

    if not data_path.is_file():
        raise FileNotFoundError(
            f"CREMI file not found: {data_path}\n"
            "Pass the correct location with --data /path/to/sampleA.h5."
        )

    print(f"Loading CREMI data from {data_path}")
    with h5py.File(data_path, "r") as file:
        for dataset_name in (RAW_DATASET, LABEL_DATASET):
            if dataset_name not in file:
                raise KeyError(
                    f"Required dataset '{dataset_name}' is missing from {data_path}"
                )

        raw_dataset = file[RAW_DATASET]
        label_dataset = file[LABEL_DATASET]
        if raw_dataset.shape != label_dataset.shape:
            raise ValueError(
                "Raw and label volumes must have identical shapes, but found "
                f"{raw_dataset.shape} and {label_dataset.shape}"
            )
        if len(raw_dataset.shape) != 3:
            raise ValueError(f"Expected a 3-D CREMI volume, found {raw_dataset.shape}")

        crop_zyx = requested_crop or centered_xy_crop(
            raw_dataset.shape, crop_size_zyx
        )
        crop_zyx = validate_crop(crop_zyx, raw_dataset.shape)
        resolution_zyx = find_resolution_zyx(file, raw_dataset, label_dataset)

        raw_zyx = np.asarray(raw_dataset[crop_zyx])
        labels_zyx = np.asarray(label_dataset[crop_zyx])

    raw_xyz = np.ascontiguousarray(raw_zyx.transpose(2, 1, 0))
    labels_xyz = np.ascontiguousarray(labels_zyx.transpose(2, 1, 0))
    resolution_xyz = np.ascontiguousarray(resolution_zyx[::-1])
    voxel_offset_xyz = np.asarray(
        [crop_zyx[2].start, crop_zyx[1].start, crop_zyx[0].start], dtype=np.int64
    )

    print(f"  full axis order: ZYX; application axis order: XYZ")
    print(f"  crop shape XYZ: {raw_xyz.shape}")
    print(f"  voxel resolution XYZ: {resolution_xyz.tolist()} nm")
    print(f"  voxel offset XYZ: {voxel_offset_xyz.tolist()}")
    print(
        "  memory: "
        f"raw={raw_xyz.nbytes / 1e6:.1f} MB, "
        f"labels={labels_xyz.nbytes / 1e6:.1f} MB"
    )

    return VolumeData(
        raw_xyz=raw_xyz,
        labels_xyz=labels_xyz,
        resolution_xyz=resolution_xyz,
        voxel_offset_xyz=voxel_offset_xyz,
        crop_zyx=crop_zyx,
    )


def array_sha256(array: np.ndarray) -> str:
    """Hash a contiguous NumPy array without creating another full-size copy."""

    contiguous = np.ascontiguousarray(array)
    digest = hashlib.sha256()
    digest.update(memoryview(contiguous).cast("B"))
    return digest.hexdigest()


def slices_as_ranges(slices: Sequence[slice]) -> list[list[int]]:
    return [[int(value.start), int(value.stop)] for value in slices]


def make_metadata(
    data_path: Path,
    data: VolumeData,
    block_shape_xyz: tuple[int, int, int],
    number_of_supervoxels: int,
) -> dict[str, Any]:
    """Use the notebook-compatible metadata fields plus a content fingerprint."""

    return {
        "source": str(data_path),
        "crop_zyx": slices_as_ranges(data.crop_zyx),
        "block_shape_xyz": list(block_shape_xyz),
        "supervoxel_shape_xyz": list(data.labels_xyz.shape),
        "number_of_supervoxels": int(number_of_supervoxels),
        "resolution_xyz_nm": [float(value) for value in data.resolution_xyz],
        "labels_sha256": array_sha256(data.labels_xyz),
    }


def compatible_metadata(saved: dict[str, Any], current: dict[str, Any]) -> bool:
    """Compare fields that determine supervoxel and graph identity.

    Older notebook state lacks the resolution and content hash. Those fields are
    checked when available but are not required for backward compatibility.
    """

    required_keys = (
        "crop_zyx",
        "block_shape_xyz",
        "supervoxel_shape_xyz",
        "number_of_supervoxels",
    )
    if any(saved.get(key) != current.get(key) for key in required_keys):
        return False

    for optional_key in ("resolution_xyz_nm", "labels_sha256"):
        if optional_key in saved and saved[optional_key] != current.get(optional_key):
            return False
    return True


def atomic_write_json(path: Path, value: Any) -> None:
    """Write JSON through a temporary file so interrupted saves stay recoverable."""

    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(json.dumps(value, indent=2) + "\n", encoding="utf-8")
    os.replace(temporary, path)


def atomic_save_numpy(path: Path, array: np.ndarray) -> None:
    """Atomically save a NumPy array."""

    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    with temporary.open("wb") as output:
        np.save(output, array, allow_pickle=False)
    os.replace(temporary, path)


def iter_blocks(
    shape_xyz: Sequence[int], block_shape_xyz: Sequence[int]
) -> Iterable[tuple[slice, slice, slice]]:
    """Yield XYZ block slices covering an array."""

    for x0 in range(0, shape_xyz[0], block_shape_xyz[0]):
        for y0 in range(0, shape_xyz[1], block_shape_xyz[1]):
            for z0 in range(0, shape_xyz[2], block_shape_xyz[2]):
                yield (
                    slice(x0, min(x0 + block_shape_xyz[0], shape_xyz[0])),
                    slice(y0, min(y0 + block_shape_xyz[1], shape_xyz[1])),
                    slice(z0, min(z0 + block_shape_xyz[2], shape_xyz[2])),
                )


def construct_supervoxels(
    labels_xyz: np.ndarray,
    output_xyz: np.ndarray,
    block_shape_xyz: tuple[int, int, int],
    refresh: Callable[[], None] | None = None,
    refresh_every: int = 4,
) -> int:
    """Subdivide each supplied neuron into connected, block-local supervoxels."""

    if labels_xyz.shape != output_xyz.shape:
        raise ValueError("Label and supervoxel arrays must have identical shapes")
    if output_xyz.dtype != np.uint32:
        raise ValueError("The supervoxel output array must use uint32")

    output_xyz.fill(0)
    connectivity = ndimage.generate_binary_structure(rank=3, connectivity=1)
    blocks = list(iter_blocks(labels_xyz.shape, block_shape_xyz))
    next_supervoxel_id = 1

    ignored_ids = {0}
    if np.issubdtype(labels_xyz.dtype, np.integer):
        ignored_ids.add(int(np.iinfo(labels_xyz.dtype).max))

    for block_number, region in enumerate(
        tqdm(blocks, desc="Constructing supervoxels", unit="block")
    ):
        label_block = labels_xyz[region]
        output_block = output_xyz[region]

        for neuron_id in np.unique(label_block):
            if int(neuron_id) in ignored_ids:
                continue

            pieces, number_of_pieces = ndimage.label(
                label_block == neuron_id, structure=connectivity
            )
            for local_piece_id in range(1, number_of_pieces + 1):
                if next_supervoxel_id > np.iinfo(np.uint32).max:
                    raise OverflowError("The crop contains too many uint32 supervoxels")
                output_block[pieces == local_piece_id] = next_supervoxel_id
                next_supervoxel_id += 1

        if refresh is not None and block_number % max(1, refresh_every) == 0:
            refresh()

    if refresh is not None:
        refresh()
    return next_supervoxel_id - 1


def build_supervoxel_graph(
    supervoxels_xyz: np.ndarray,
    original_labels_xyz: np.ndarray,
    resolution_xyz: np.ndarray,
) -> nx.Graph:
    """Connect touching supervoxels that came from the same supplied neuron."""

    graph = nx.Graph()
    node_ids = np.unique(supervoxels_xyz)
    graph.add_nodes_from(int(node) for node in node_ids if node != 0)

    for axis in tqdm(range(3), desc="Building adjacency graph", unit="axis"):
        left_slice = [slice(None)] * 3
        right_slice = [slice(None)] * 3
        left_slice[axis] = slice(0, -1)
        right_slice[axis] = slice(1, None)
        left = tuple(left_slice)
        right = tuple(right_slice)

        left_sv = supervoxels_xyz[left]
        right_sv = supervoxels_xyz[right]
        left_labels = original_labels_xyz[left]
        right_labels = original_labels_xyz[right]

        valid = (
            (left_sv != 0)
            & (right_sv != 0)
            & (left_sv != right_sv)
            & (left_labels == right_labels)
        )
        if not np.any(valid):
            continue

        first = left_sv[valid].astype(np.uint64)
        second = right_sv[valid].astype(np.uint64)
        pairs = np.stack(
            [np.minimum(first, second), np.maximum(first, second)], axis=1
        )
        unique_pairs, face_counts = np.unique(pairs, axis=0, return_counts=True)

        other_axes = [index for index in range(3) if index != axis]
        face_area_nm2 = float(
            resolution_xyz[other_axes[0]] * resolution_xyz[other_axes[1]]
        )

        for pair, face_count in zip(unique_pairs, face_counts):
            u, v = int(pair[0]), int(pair[1])
            capacity = float(face_count * face_area_nm2)
            if graph.has_edge(u, v):
                graph[u][v]["capacity"] += capacity
            else:
                graph.add_edge(u, v, capacity=capacity, kind="initial")
    return graph


def graph_components_and_roots(
    graph: nx.Graph,
) -> tuple[list[list[int]], dict[int, int]]:
    """Convert graph components into Neuroglancer equivalence groups."""

    components = [
        sorted(int(node) for node in component)
        for component in nx.connected_components(graph)
    ]
    roots = {
        node: min(component) for component in components for node in component
    }
    return components, roots


def graph_to_json(
    graph: nx.Graph, metadata: dict[str, Any], history: list[dict[str, Any]]
) -> dict[str, Any]:
    """Serialize the editable graph with plain JSON-compatible values."""

    edges = []
    for u, v, attributes in graph.edges(data=True):
        capacity = float(attributes.get("capacity", 1.0))
        if not math.isfinite(capacity) or capacity <= 0:
            raise ValueError(f"Invalid capacity on edge {u}-{v}: {capacity}")
        edges.append(
            {
                "u": int(u),
                "v": int(v),
                "capacity": capacity,
                "kind": str(attributes.get("kind", "unknown")),
            }
        )
    edges.sort(key=lambda edge: (edge["u"], edge["v"]))
    return {
        "version": 1,
        "metadata": metadata,
        "edges": edges,
        "history": history,
    }


def graph_from_json(
    value: dict[str, Any], node_ids: set[int], metadata: dict[str, Any]
) -> tuple[nx.Graph, list[dict[str, Any]]]:
    """Validate and restore a saved graph."""

    if value.get("version") != 1:
        raise ValueError(f"Unsupported edit-state version: {value.get('version')!r}")
    saved_metadata = value.get("metadata")
    if not isinstance(saved_metadata, dict) or not compatible_metadata(
        saved_metadata, metadata
    ):
        raise ValueError(
            "Saved edits do not match this dataset crop and supervoxel volume. "
            "Use a different --state-dir or explicitly pass --reset-state."
        )

    graph = nx.Graph()
    graph.add_nodes_from(node_ids)
    for edge in value.get("edges", []):
        u, v = int(edge["u"]), int(edge["v"])
        if u not in node_ids or v not in node_ids:
            raise ValueError(f"Saved edge {u}-{v} refers to an unknown supervoxel")
        capacity = float(edge.get("capacity", 1.0))
        if not math.isfinite(capacity) or capacity <= 0:
            raise ValueError(f"Saved edge {u}-{v} has invalid capacity {capacity}")
        graph.add_edge(
            u, v, capacity=capacity, kind=str(edge.get("kind", "unknown"))
        )

    history = value.get("history", [])
    if not isinstance(history, list):
        raise ValueError("Saved edit history must be a list")
    return graph, history


def reset_known_state_files(paths: StatePaths) -> None:
    """Remove only the files generated by this application."""

    for path in (paths.supervoxels, paths.preprocessing, paths.edits):
        if path.exists():
            print(f"Removing generated state file: {path}")
            path.unlink()


def load_cached_supervoxels(
    paths: StatePaths,
    data: VolumeData,
    block_shape_xyz: tuple[int, int, int],
) -> tuple[np.ndarray | None, dict[str, Any] | None]:
    """Load a compatible cache, including state produced by the notebook."""

    if not paths.supervoxels.exists():
        return None, None

    supervoxels = np.load(paths.supervoxels, allow_pickle=False)
    if supervoxels.dtype != np.uint32 or supervoxels.shape != data.labels_xyz.shape:
        raise ValueError(
            f"Incompatible cached supervoxel array at {paths.supervoxels}. "
            "Use a different --state-dir or explicitly pass --reset-state."
        )

    number_of_supervoxels = int(supervoxels.max(initial=0))
    current_metadata = make_metadata(
        data_path=Path("unused-for-identity"),
        data=data,
        block_shape_xyz=block_shape_xyz,
        number_of_supervoxels=number_of_supervoxels,
    )

    saved_metadata: dict[str, Any] | None = None
    if paths.preprocessing.exists():
        preprocessing = json.loads(paths.preprocessing.read_text(encoding="utf-8"))
        saved_metadata = preprocessing.get("metadata")
    elif paths.edits.exists():
        # Backward compatibility with the original notebook, which saved the
        # metadata only inside edits.json.
        edits = json.loads(paths.edits.read_text(encoding="utf-8"))
        saved_metadata = edits.get("metadata")

    if not isinstance(saved_metadata, dict):
        raise ValueError(
            f"Found {paths.supervoxels} without compatible metadata. "
            "Use a different --state-dir or explicitly pass --reset-state."
        )
    if not compatible_metadata(saved_metadata, current_metadata):
        raise ValueError(
            "Cached supervoxels do not match the requested crop or block shape. "
            "Use a different --state-dir or explicitly pass --reset-state."
        )
    return np.ascontiguousarray(supervoxels), current_metadata


class NeuroglancerScene:
    """Owns all arrays and viewer layers used by the application."""

    def __init__(self, data: VolumeData, supervoxels_xyz: np.ndarray):
        self.data = data
        self.supervoxels_xyz = supervoxels_xyz
        self.dimensions = neuroglancer.CoordinateSpace(
            names=["x", "y", "z"],
            units=["nm", "nm", "nm"],
            scales=data.resolution_xyz,
        )

        self.raw_volume = neuroglancer.LocalVolume(
            data=data.raw_xyz,
            dimensions=self.dimensions,
            voxel_offset=data.voxel_offset_xyz,
            volume_type="image",
        )
        self.original_label_volume = neuroglancer.LocalVolume(
            data=data.labels_xyz,
            dimensions=self.dimensions,
            voxel_offset=data.voxel_offset_xyz,
            volume_type="segmentation",
        )
        self.supervoxel_volume = neuroglancer.LocalVolume(
            data=supervoxels_xyz,
            dimensions=self.dimensions,
            voxel_offset=data.voxel_offset_xyz,
            volume_type="segmentation",
            mesh_options={
                "max_quadrics_error": 1e5,
                "max_normal_angle_deviation": 90,
                "lock_boundary_vertices": True,
            },
        )
        self.viewer = neuroglancer.Viewer()
        self._add_initial_layers()

    def _add_initial_layers(self) -> None:
        with self.viewer.txn() as state:
            state.dimensions = self.dimensions
            state.position = self.data.voxel_offset_xyz + np.asarray(
                self.data.raw_xyz.shape, dtype=float
            ) / 2
            state.layers[EM_LAYER] = neuroglancer.ImageLayer(
                source=self.raw_volume,
                opacity=1.0,
                shader="""
void main() {
  emitGrayscale(toNormalized(getDataValue()));
}
""",
            )
            state.layers[ORIGINAL_LABEL_LAYER] = neuroglancer.SegmentationLayer(
                source=self.original_label_volume,
                selected_alpha=0.8,
                not_selected_alpha=0.25,
                object_alpha=0.5,
            )
            state.layers[SUPERVOXEL_LAYER] = neuroglancer.SegmentationLayer(
                source=self.supervoxel_volume,
                selected_alpha=0.8,
                not_selected_alpha=0.35,
                object_alpha=0.5,
            )
            state.layers[SUPERVOXEL_LAYER].visible = False
            state.layout = "xy"

    def show_live_supervoxel_construction(self) -> None:
        with self.viewer.txn() as state:
            state.layers[ORIGINAL_LABEL_LAYER].visible = False
            state.layers[SUPERVOXEL_LAYER].visible = True
        self.set_status("Constructing supervoxels; watch them appear in the viewer")

    def invalidate_supervoxels(self) -> None:
        self.supervoxel_volume.invalidate()

    def set_status(self, message: str) -> None:
        print(message)
        with self.viewer.config_state.txn() as config:
            config.status_messages["application"] = message


class SegmentationEditor:
    """Interactive graph editor connected to a Neuroglancer viewer."""

    def __init__(
        self,
        scene: NeuroglancerScene,
        graph: nx.Graph,
        metadata: dict[str, Any],
        history: list[dict[str, Any]],
        edits_path: Path,
    ):
        self.scene = scene
        self.viewer = scene.viewer
        self.graph = graph
        self.metadata = metadata
        self.history = history
        self.edits_path = edits_path
        self.seed_a: int | None = None
        self.seed_b: int | None = None
        self.seed_a_position: np.ndarray | None = None
        self.seed_b_position: np.ndarray | None = None
        self.roots: dict[int, int] = {}
        self.lock = threading.RLock()

        self._add_editor_layers()
        self._register_actions()
        self.refresh_viewer()
        self.save()
        self.set_status("Editor ready")

    def _add_editor_layers(self) -> None:
        with self.viewer.txn() as state:
            state.layers[OBJECT_LAYER] = neuroglancer.SegmentationLayer(
                source=self.scene.supervoxel_volume,
                selected_alpha=0.9,
                not_selected_alpha=0.25,
                object_alpha=0.7,
            )
            state.layers[SEED_A_LAYER] = neuroglancer.LocalAnnotationLayer(
                dimensions=self.scene.dimensions, annotation_color="#00ff00"
            )
            state.layers[SEED_B_LAYER] = neuroglancer.LocalAnnotationLayer(
                dimensions=self.scene.dimensions, annotation_color="#ff00ff"
            )
            state.layers[ORIGINAL_LABEL_LAYER].visible = False
            state.layers[SUPERVOXEL_LAYER].visible = False
            state.layout = neuroglancer.row_layout(
                [
                    neuroglancer.LayerGroupViewer(
                        layout="xy",
                        layers=[
                            EM_LAYER,
                            OBJECT_LAYER,
                            ORIGINAL_LABEL_LAYER,
                            SUPERVOXEL_LAYER,
                            SEED_A_LAYER,
                            SEED_B_LAYER,
                        ],
                    ),
                    neuroglancer.LayerGroupViewer(
                        layout="3d",
                        layers=[OBJECT_LAYER, SEED_A_LAYER, SEED_B_LAYER],
                    ),
                ]
            )

    def _register_actions(self) -> None:
        self.viewer.actions.add("choose-seed-a", self.choose_seed_a)
        self.viewer.actions.add("choose-seed-b", self.choose_seed_b)
        self.viewer.actions.add("merge-seeds", self.merge)
        self.viewer.actions.add("split-seeds", self.split)
        self.viewer.actions.add("clear-seeds", self.clear_seeds)

        with self.viewer.config_state.txn() as config:
            config.input_event_bindings.data_view[
                "shift+mousedown0"
            ] = "choose-seed-a"
            config.input_event_bindings.data_view[
                "control+mousedown0"
            ] = "choose-seed-b"
            config.input_event_bindings.data_view["alt+mousedown0"] = "choose-seed-b"
            config.input_event_bindings.data_view["keym"] = "merge-seeds"
            config.input_event_bindings.data_view["keys"] = "split-seeds"
            config.input_event_bindings.data_view["keyc"] = "clear-seeds"
            config.status_messages["help"] = (
                "Shift-click=A | Ctrl/Option-click=B | M=merge | S=split | C=clear"
            )

    def selected_supervoxel(self, action_state: Any) -> int | None:
        """Read the raw supervoxel under the mouse from either segmentation layer."""

        for layer_name in (OBJECT_LAYER, SUPERVOXEL_LAYER):
            selected = action_state.selected_values.get(layer_name)
            if selected is None:
                continue
            value = selected.value
            if isinstance(value, neuroglancer.SegmentIdMapEntry):
                return int(value.key)
            if value is not None:
                return int(value)
        return None

    @staticmethod
    def mouse_position(action_state: Any) -> np.ndarray | None:
        position = action_state.mouse_voxel_coordinates
        if position is None:
            return None
        return np.asarray(position, dtype=float)

    def choose_seed_a(self, action_state: Any) -> None:
        with self.lock:
            supervoxel = self.selected_supervoxel(action_state)
            position = self.mouse_position(action_state)
            if supervoxel is None or position is None:
                self.set_status("Seed A must be placed on the object segmentation")
                return
            self.seed_a = supervoxel
            self.seed_a_position = position
            self.update_seed_annotations()
            self.refresh_viewer()
            self.set_status(f"Seed A = supervoxel {supervoxel}")

    def choose_seed_b(self, action_state: Any) -> None:
        with self.lock:
            supervoxel = self.selected_supervoxel(action_state)
            position = self.mouse_position(action_state)
            if supervoxel is None or position is None:
                self.set_status("Seed B must be placed on the object segmentation")
                return
            self.seed_b = supervoxel
            self.seed_b_position = position
            self.update_seed_annotations()
            self.refresh_viewer()
            self.set_status(f"Seed B = supervoxel {supervoxel}")

    def _ensure_annotation_layer(
        self, state: Any, name: str, color: str
    ) -> Any:
        """Repair stale/wrong seed layers before assigning annotations."""

        missing = name not in state.layers
        wrong_type = not missing and not hasattr(state.layers[name].layer, "annotations")
        if missing or wrong_type:
            state.layers[name] = neuroglancer.LocalAnnotationLayer(
                dimensions=self.scene.dimensions, annotation_color=color
            )
        return state.layers[name]

    def update_seed_annotations(self) -> None:
        with self.viewer.txn() as state:
            seed_a_layer = self._ensure_annotation_layer(
                state, SEED_A_LAYER, "#00ff00"
            )
            seed_b_layer = self._ensure_annotation_layer(
                state, SEED_B_LAYER, "#ff00ff"
            )

            seed_a_layer.annotations = (
                []
                if self.seed_a_position is None
                else [
                    neuroglancer.PointAnnotation(
                        id="seed-a",
                        point=self.seed_a_position,
                        description=f"A: supervoxel {self.seed_a}",
                    )
                ]
            )
            seed_b_layer.annotations = (
                []
                if self.seed_b_position is None
                else [
                    neuroglancer.PointAnnotation(
                        id="seed-b",
                        point=self.seed_b_position,
                        description=f"B: supervoxel {self.seed_b}",
                    )
                ]
            )

    def refresh_viewer(self) -> None:
        components, self.roots = graph_components_and_roots(self.graph)
        selected_nodes = {
            node for node in (self.seed_a, self.seed_b) if node is not None
        }
        visible_roots = {
            self.roots[node] for node in selected_nodes if node in self.roots
        }
        with self.viewer.txn() as state:
            layer = state.layers[OBJECT_LAYER]
            layer.equivalences = components
            layer.segments = visible_roots

    def merge(self, _action_state: Any = None) -> None:
        with self.lock:
            if self.seed_a is None or self.seed_b is None:
                self.set_status("Choose both seed A and seed B before merging")
                return
            if self.seed_a == self.seed_b:
                self.set_status("A and B are the same supervoxel")
                return
            if self.roots[self.seed_a] == self.roots[self.seed_b]:
                self.set_status("A and B already belong to the same object")
                return

            self.graph.add_edge(
                self.seed_a,
                self.seed_b,
                capacity=1.0,
                kind="manual-merge",
            )
            self.history.append(
                {"operation": "merge", "a": self.seed_a, "b": self.seed_b}
            )
            self.refresh_viewer()
            self.save()
            self.set_status(
                f"Merged objects through edge {self.seed_a}-{self.seed_b}"
            )

    def split(self, _action_state: Any = None) -> None:
        with self.lock:
            if self.seed_a is None or self.seed_b is None:
                self.set_status("Choose both seed A and seed B before splitting")
                return
            if self.seed_a == self.seed_b:
                self.set_status("A and B must be different supervoxels")
                return
            if self.roots[self.seed_a] != self.roots[self.seed_b]:
                self.set_status("A and B already belong to different objects")
                return

            component_nodes = nx.node_connected_component(self.graph, self.seed_a)
            component = self.graph.subgraph(component_nodes).copy()
            cut_value, (left, right) = nx.minimum_cut(
                component, self.seed_a, self.seed_b, capacity="capacity"
            )
            cut_edges = sorted(
                {
                    tuple(sorted((int(u), int(v))))
                    for u in left
                    for v in self.graph.neighbors(u)
                    if v in right
                }
            )
            if not cut_edges:
                self.set_status("No graph edges were found for this split")
                return

            self.graph.remove_edges_from(cut_edges)
            self.history.append(
                {
                    "operation": "split",
                    "a": self.seed_a,
                    "b": self.seed_b,
                    "cut_value": float(cut_value),
                    "removed_edges": [list(edge) for edge in cut_edges],
                }
            )
            self.refresh_viewer()
            self.save()
            self.set_status(f"Split object by removing {len(cut_edges)} graph edges")

    def clear_seeds(self, _action_state: Any = None) -> None:
        with self.lock:
            self.seed_a = None
            self.seed_b = None
            self.seed_a_position = None
            self.seed_b_position = None
            self.update_seed_annotations()
            self.refresh_viewer()
            self.set_status("Selections cleared")

    def set_status(self, message: str) -> None:
        print(message)
        with self.viewer.config_state.txn() as config:
            config.status_messages["editor"] = message

    def save(self) -> None:
        atomic_write_json(
            self.edits_path,
            graph_to_json(self.graph, self.metadata, self.history),
        )


